; ============================================================================
; QX11_MATRIX_RAIN_PROTO_V7.ASM
; Epson QX-11 / QC-11 Matrix rain FINAL V10
;
; V5 keeps the smooth V4 one-scanline streaming engine.
;
; New visual behavior:
;   * startup begins with ONE RANDOM active stream
;   * additional streams are enabled gradually in RANDOM columns
;   * a stream grows naturally: 1 char, then 2, then 3...
;   * random holes appear inside active trails
;   * streams stop and collapse as blanks enter behind them
;   * occasional HOT characters are drawn thicker/brighter
;   * glyphs are pseudo-random instead of cycling
;
; FINAL V10 adds:
;   * UP/DOWN control of QX-11 INT 71h interval at 0000:2180h
;   * UP decreases interval (faster), DOWN increases it (slower)
;   * range 0100h..0F00h, step 0100h
;   * visible DelayCount follows the ticker setting
;   * ESC/normal exit restores 0000:2180h to Epson default 0600h
;
; FINAL V9 adds:
;   * rare hardware screen shake using the proven C462/C663 display origin
;   * shake perturbs display only; logical OriginY remains untouched
;   * randomized delay between shakes
;   * final tweak: some shakes trigger a short GLITCH BURST that increases
;     the chance of rapid visible-character flicker for a few character periods
;
; V8 keeps V7 dynamic mutation and adds:
;   * expanded Matrix font: Katakana + Hiragana + digits + Latin + symbols
;   * rapid flicker bursts on visible cells
;   * flicker can cycle NORMAL -> HOT -> INVERSE -> another glyph
;   * inverse is done directly in VRAM bitmap generation (NOT AL)
;
; V7 adds dynamic mutation of already-visible characters:
;   * every stream has a 16-bit occupancy history for the last 16 cells
;   * once per character period there is a 50% chance of one mutation
;   * mutation chooses a random occupied stream/cell
;   * only that one 16x16 glyph is redrawn (32 VRAM byte writes)
;   * about 1/8 mutations use the HOT/thick rendering
;
; Rendering remains cheap:
;   24 streams * 2 VRAM bytes = 48 VRAM writes per scanline tick
;   plus the two GAVDP origin registers.
;
; Confirmed Mode-7 mapping:
;   byte_column = X >> 3
;   column_base = byte_column * 0x0200
;   Y 0..199    -> 8000:column_base+Y
;   Y 200..399  -> 8010:column_base+(Y-200)
;
; Confirmed composite vertical origin:
;   origin 0..199   => C462=00, C663=origin
;   origin 200..399 => C462=80, C663=origin-200
;
; Controls:
;   SPACE   pause/resume
;   UP      faster: 0000:2180h -= 0100h
;   DOWN    slower: 0000:2180h += 0100h
;   1..4    legacy direct DelayCount presets
;   R       restart from one stream
;   ESC     restore 0000:2180h=0600h and exit
;
; Build:
;   nasm -f bin QX11_MATRIX_RAIN_PROTO_V7.ASM -o QXMATRIX.COM
; ============================================================================

VRAM_UPPER_SEG     equ 0x8000
VRAM_LOWER_SEG     equ 0x8010
VRAM_COL_STRIDE    equ 0x0200
VRAM_COLS          equ 80
VRAM_BANK_ROWS     equ 200

GAVDP_CONTROL      equ 0xC060
GAVDP_AUX          equ 0xD068
GAVDP_ORIGIN_AUX   equ 0xC261
GAVDP_HORIGIN      equ 0xC462
GAVDP_VORIGIN      equ 0xC663

BDA_SEG            equ 0x0040
BDA_VIDEO_MODE     equ 0x0049

STREAM_COUNT       equ 24
GLYPH_COUNT        equ 96

; Stream record
ST_X               equ 0
ST_ENABLED         equ 1
ST_WAIT            equ 2
ST_ACTIVE          equ 3
ST_TOTAL           equ 4
ST_GLYPH           equ 5
ST_LEVEL           equ 6
ST_HOT             equ 7
STREAM_SIZE        equ 8

start:
        push    cs
        pop     ds
        cld

        mov     ah,0x0F
        int     0x10
        mov     [OldVideoMode],al

        mov     ax,0x0007
        int     0x10
        push    cs
        pop     ds

        push    es
        mov     ax,BDA_SEG
        mov     es,ax
        cmp     byte [es:BDA_VIDEO_MODE],0x07
        pop     es
        jne     WrongVideoConfiguration

        mov     ah,0x01
        mov     cx,0x2000
        int     0x10
        push    cs
        pop     ds

        call    InitializeGAVDP
        call    ResetRain

MainLoop:
        call    PollKeyboard
        cmp     byte [ExitRequested],0
        jne     ExitProgram

        cmp     byte [Paused],0
        jne     .delay

        mov     ax,[OriginY]
        or      ax,ax
        jnz     .have_next
        mov     ax,400
.have_next:
        dec     ax
        mov     [NextOriginY],ax

        call    RenderEnteringScanline

        mov     ax,[NextOriginY]
        mov     [OriginY],ax

        ; Rare camera shake. This changes only what is written to C462/C663;
        ; OriginY itself continues advancing normally.
        call    UpdateScreenShake
        call    WriteVerticalOrigin

        ; Rapid-flicker event, if one is active. This redraws only one 16x16
        ; visible cell and is intentionally conspicuous.
        call    UpdateRapidFlicker

        inc     byte [PixelPhase]
        cmp     byte [PixelPhase],16
        jb      .delay

        mov     byte [PixelPhase],0
        call    AdvanceCharacters
        call    StartupRamp
        call    MaybeMutateVisibleCharacter
        call    MaybeStartRapidFlicker

.delay:
        call    FrameDelay
        jmp     MainLoop

WrongVideoConfiguration:
        call    RestoreDefaultTicker
        xor     ax,ax
        mov     al,[OldVideoMode]
        int     0x10
        mov     dx,WrongModeMessage
        mov     ah,0x09
        int     0x21
        mov     ax,0x4C01
        int     0x21

ExitProgram:
        mov     word [OriginY],0
        call    WriteVerticalOrigin
        call    RestoreDefaultTicker

        xor     ax,ax
        mov     al,[OldVideoMode]
        int     0x10

        mov     ax,0x4C00
        int     0x21

; ============================================================================
; GAVDP
; ============================================================================

InitializeGAVDP:
        push    ax
        push    es

        mov     ax,VRAM_UPPER_SEG
        mov     es,ax

        mov     byte [es:GAVDP_CONTROL],0x35
        mov     byte [es:GAVDP_AUX],0x02
        mov     byte [es:GAVDP_ORIGIN_AUX],0x00
        mov     byte [es:GAVDP_HORIGIN],0x00
        mov     byte [es:GAVDP_VORIGIN],0x00

        pop     es
        pop     ax
        ret

WriteVerticalOrigin:
        push    ax
        push    bx
        push    dx
        push    es

        ; BX = logical origin.  During a shake, add a small signed Y offset
        ; WITHOUT changing OriginY itself.
        mov     bx,[OriginY]

        cmp     byte [ShakeActive],0
        je      .y_ready

        xor     ax,ax
        mov     al,[ShakeYOffset]
        cbw
        add     bx,ax

        ; modulo 400, supporting small negative offsets.
        cmp     bx,0x8000
        jb      .not_negative
        add     bx,400
.not_negative:
        cmp     bx,400
        jb      .y_ready
        sub     bx,400

.y_ready:
        xor     al,al

        cmp     bx,200
        jb      .upper

        sub     bx,200
        mov     al,0x80

.upper:
        ; Preserve C462 bit 7 as the vertical-half selector and use its low
        ; bits for the small horizontal shake offset.
        cmp     byte [ShakeActive],0
        je      .no_xshake
        or      al,[ShakeXOffset]
.no_xshake:
        mov     [RegC462],al
        mov     [RegC663],bl

        mov     ax,VRAM_UPPER_SEG
        mov     es,ax

        mov     al,[RegC663]
        mov     [es:GAVDP_VORIGIN],al

        mov     al,[RegC462]
        mov     [es:GAVDP_HORIGIN],al

        pop     es
        pop     dx
        pop     bx
        pop     ax
        ret

; ============================================================================
; One-scanline renderer
; ============================================================================

RenderEnteringScanline:
        push    ax
        push    bx
        push    cx
        push    dx
        push    si
        push    di

        mov     al,15
        sub     al,[PixelPhase]
        mov     [SourceGlyphRow],al

        mov     dx,[NextOriginY]
        mov     si,Streams
        mov     cx,STREAM_COUNT

.next_stream:
        push    cx

        xor     bx,bx
        mov     bl,[si+ST_X]

        cmp     byte [si+ST_ENABLED],0
        je      .blank

        mov     al,[si+ST_GLYPH]
        cmp     al,0xFF
        je      .blank

        xor     ah,ah
        mov     di,ax

        shl     di,1
        shl     di,1
        shl     di,1
        shl     di,1
        shl     di,1

        xor     ax,ax
        mov     al,[SourceGlyphRow]
        add     di,ax
        add     di,FontBank

        ; left 8 pixels
        mov     al,[di]
        mov     ah,[si+ST_LEVEL]
        call    ApplyDitherRow
        cmp     byte [si+ST_HOT],0
        je      .left_ready
        call    MakeHot
.left_ready:
        call    WriteVRAMByte

        ; right 8 pixels
        inc     bx
        mov     al,[di+16]
        mov     ah,[si+ST_LEVEL]
        call    ApplyDitherRow
        cmp     byte [si+ST_HOT],0
        je      .right_ready
        call    MakeHot
.right_ready:
        call    WriteVRAMByte
        jmp     .advance

.blank:
        xor     al,al
        call    WriteVRAMByte
        inc     bx
        xor     al,al
        call    WriteVRAMByte

.advance:
        add     si,STREAM_SIZE
        pop     cx
        loop    .next_stream

        pop     di
        pop     si
        pop     dx
        pop     cx
        pop     bx
        pop     ax
        ret

; IN AL bitmap byte
; "Hot" glyph = slightly expanded horizontally.
MakeHot:
        push    bx
        mov     bl,al
        shr     bl,1
        or      al,bl
        mov     bl,al
        shl     bl,1
        or      al,bl
        pop     bx
        ret

WriteVRAMByte:
        push    ax
        push    bx
        push    cx
        push    dx
        push    di
        push    es

        mov     di,bx
        mov     cl,9
        shl     di,cl

        cmp     dx,200
        jb      .upper

        sub     dx,200
        mov     bx,VRAM_LOWER_SEG
        jmp     .segready

.upper:
        mov     bx,VRAM_UPPER_SEG

.segready:
        mov     es,bx
        add     di,dx
        mov     [es:di],al

        pop     es
        pop     di
        pop     dx
        pop     cx
        pop     bx
        pop     ax
        ret

ApplyDitherRow:
        push    bx

        or      ah,ah
        jz      .done

        mov     bl,[SourceGlyphRow]
        test    bl,1
        jnz     .odd

        cmp     ah,1
        jne     .even2
        and     al,0xDD
        jmp     .done
.even2:
        cmp     ah,2
        jne     .even3
        and     al,0xAA
        jmp     .done
.even3:
        and     al,0x88
        jmp     .done

.odd:
        cmp     ah,1
        jne     .odd2
        and     al,0x77
        jmp     .done
.odd2:
        cmp     ah,2
        jne     .odd3
        and     al,0x55
        jmp     .done
.odd3:
        and     al,0x22

.done:
        pop     bx
        ret

; ============================================================================
; Stream logic
; ============================================================================

; Every complete 16-pixel character interval.
AdvanceCharacters:
        push    ax
        push    bx
        push    cx
        push    di
        push    si

        mov     si,Streams
        mov     di,OccupancyHistory
        mov     cx,STREAM_COUNT

.next:
        push    cx

        ; OccupancyHistory bit 0 = newest fully visible character cell.
        ; Shift older cells down by one position, then record the character
        ; that just finished entering during the previous 16 scanline ticks.
        shl     word [di],1
        cmp     byte [si+ST_ENABLED],0
        je      .occupancy_done
        cmp     byte [si+ST_GLYPH],0xFF
        je      .occupancy_done
        or      word [di],1
.occupancy_done:

        cmp     byte [si+ST_ENABLED],0
        je      .advance

        cmp     byte [si+ST_WAIT],0
        je      .not_waiting

        dec     byte [si+ST_WAIT]
        mov     byte [si+ST_GLYPH],0xFF
        mov     byte [si+ST_HOT],0
        jmp     .advance

.not_waiting:
        cmp     byte [si+ST_ACTIVE],0
        jne     .continue_burst

        call    StartBurst
        jmp     .advance

.continue_burst:
        dec     byte [si+ST_ACTIVE]

        cmp     byte [si+ST_ACTIVE],0
        jne     .emit_or_hole

        ; Stream stops. Blanks now enter and naturally erase/collapse the trail.
        call    Rand16
        and     al,0x07
        add     al,4
        mov     [si+ST_WAIT],al
        mov     byte [si+ST_GLYPH],0xFF
        mov     byte [si+ST_HOT],0
        jmp     .advance

.emit_or_hole:
        ; About 1/8 active cells become a hole.
        call    Rand16
        test    al,0x07
        jnz     .emit

        mov     byte [si+ST_GLYPH],0xFF
        mov     byte [si+ST_HOT],0
        jmp     .advance

.emit:
        call    ChooseRandomGlyph
        call    CalculateTraceLevel
        call    ChooseHot

.advance:
        add     si,STREAM_SIZE
        add     di,2
        pop     cx
        loop    .next

        pop     si
        pop     di
        pop     cx
        pop     bx
        pop     ax
        ret

StartBurst:
        push    ax

        ; 6..18 glyphs
        call    Rand16
        and     al,0x0F
        cmp     al,12
        jbe     .ok
        sub     al,7
.ok:
        add     al,6

        mov     [si+ST_TOTAL],al
        mov     [si+ST_ACTIVE],al
        mov     byte [si+ST_WAIT],0

        call    ChooseRandomGlyph
        call    CalculateTraceLevel
        call    ChooseHot

        pop     ax
        ret

ChooseRandomGlyph:
        push    ax

        call    Rand16
.mod:
        cmp     al,GLYPH_COUNT
        jb      .done
        sub     al,GLYPH_COUNT
        jmp     .mod
.done:
        mov     [si+ST_GLYPH],al

        pop     ax
        ret

; Roughly 1 in 24 emitted glyphs becomes HOT.
ChooseHot:
        push    ax

        mov     byte [si+ST_HOT],0
        call    Rand16

        and     al,0x1F
        cmp     al,1
        jne     .done

        mov     byte [si+ST_HOT],1

.done:
        pop     ax
        ret

; Newest characters become brighter as the burst progresses.
CalculateTraceLevel:
        push    ax
        push    bx
        push    dx

        xor     ax,ax
        mov     al,[si+ST_TOTAL]

        mov     bl,al
        shr     bl,1
        shr     bl,1
        cmp     bl,1
        jae     .quarter_ok
        mov     bl,1
.quarter_ok:

        xor     dx,dx
        mov     dl,[si+ST_ACTIVE]

        xor     ax,ax
        mov     al,bl
        add     al,bl
        add     al,bl
        cmp     dl,al
        jbe     .not3
        mov     byte [si+ST_LEVEL],3
        jmp     .done

.not3:
        xor     ax,ax
        mov     al,bl
        add     al,bl
        cmp     dl,al
        jbe     .not2
        mov     byte [si+ST_LEVEL],2
        jmp     .done

.not2:
        cmp     dl,bl
        jbe     .full
        mov     byte [si+ST_LEVEL],1
        jmp     .done

.full:
        mov     byte [si+ST_LEVEL],0

.done:
        pop     dx
        pop     bx
        pop     ax
        ret

; ---------------------------------------------------------------------------
; Startup density ramp - V6R
;
; ResetRain creates ActivationOrder[] as a shuffled permutation of 0..23.
; StartupRamp simply consumes that table.  Therefore every physical stream is
; activated exactly once, and the visible order cannot become 0,1,2,3... unless
; the shuffle itself somehow produced that extraordinarily unlikely permutation.
; ---------------------------------------------------------------------------
StartupRamp:
        push    ax
        push    bx
        push    si

        cmp     byte [EnabledStreams],STREAM_COUNT
        jae     .done

        inc     byte [RampCounter]
        cmp     byte [RampCounter],4
        jb      .done

        mov     byte [RampCounter],0

        xor     bx,bx
        mov     bl,[EnabledStreams]
        mov     al,[ActivationOrder+bx]      ; stream index 0..23

        xor     ah,ah
        mov     bx,ax
        shl     bx,1
        shl     bx,1
        shl     bx,1                         ; * STREAM_SIZE (8)

        mov     si,Streams
        add     si,bx

        mov     byte [si+ST_ENABLED],1
        mov     byte [si+ST_WAIT],0
        mov     byte [si+ST_ACTIVE],0
        mov     byte [si+ST_TOTAL],0
        mov     byte [si+ST_GLYPH],0xFF
        mov     byte [si+ST_LEVEL],0
        mov     byte [si+ST_HOT],0

        inc     byte [EnabledStreams]

.done:
        pop     si
        pop     bx
        pop     ax
        ret

; ---------------------------------------------------------------------------
; Build ActivationOrder = shuffled 0..23 using Fisher-Yates.
; ---------------------------------------------------------------------------
ShuffleActivationOrder:
        push    ax
        push    bx
        push    cx
        push    dx
        push    si
        push    di

        ; Initialize order[i] = i.
        xor     bx,bx
        mov     cx,STREAM_COUNT
.init:
        mov     [ActivationOrder+bx],bl
        inc     bx
        loop    .init

        ; i = 23 down to 1.  Choose j in 0..i and swap.
        mov     cl,STREAM_COUNT-1
.shuffle:
        call    Rand16

        ; Reduce AL to 0..CL using repeated subtraction.
.reduce:
        cmp     al,cl
        jbe     .j_ready
        sub     al,cl
        dec     al                          ; subtract (CL+1)
        jmp     .reduce

.j_ready:
        xor     ah,ah
        mov     di,ax                       ; DI = j

        xor     bx,bx
        mov     bl,cl                       ; BX = i

        mov     al,[ActivationOrder+bx]
        mov     dl,[ActivationOrder+di]
        mov     [ActivationOrder+bx],dl
        mov     [ActivationOrder+di],al

        dec     cl
        jnz     .shuffle

        pop     di
        pop     si
        pop     dx
        pop     cx
        pop     bx
        pop     ax
        ret

; ---------------------------------------------------------------------------
; Dynamic Matrix character mutation.
;
; Called only at a 16-pixel character boundary, so OriginY is aligned with
; OccupancyHistory cell positions:
;       bit 0 -> logical Y = 0
;       bit 1 -> logical Y = 16
;       ...
;       bit15 -> logical Y = 240
;
; 50% of character periods do nothing.  Otherwise choose a random stream that
; has at least one occupied cell, choose one occupied cell, and replace it with
; a different random Kana.  This touches only one 16x16 cell.
; ---------------------------------------------------------------------------
MaybeMutateVisibleCharacter:
        push    ax
        push    bx
        push    cx
        push    dx
        push    si
        push    di
        push    bp

        call    Rand16
        test    al,1
        jnz     .done                    ; 50% chance: no mutation this period

        mov     bp,STREAM_COUNT          ; bounded retry count

.try_stream:
        call    RandomStreamIndex        ; AL = stream index 0..23
        xor     ah,ah
        mov     [MutationStreamIndex],ax

        ; DI -> occupancy word for selected stream.
        mov     di,ax
        shl     di,1
        add     di,OccupancyHistory
        mov     dx,[di]
        or      dx,dx
        jnz     .have_stream

        dec     bp
        jnz     .try_stream
        jmp     .done                    ; no occupied stream found yet

.have_stream:
        ; Pick a random starting cell 0..15, then scan cyclically until we
        ; encounter an occupied bit.
        call    Rand16
        and     al,0x0F
        mov     [MutationCell],al
        mov     cx,16

.find_cell:
        xor     bx,bx
        mov     bl,[MutationCell]

        mov     ax,1
        push    cx
        mov     cl,bl
        shl     ax,cl
        pop     cx

        test    dx,ax
        jnz     .cell_found

        inc     byte [MutationCell]
        and     byte [MutationCell],0x0F
        loop    .find_cell
        jmp     .done

.cell_found:
        ; Rebuild SI -> selected stream record (record size remains 8 bytes).
        mov     ax,[MutationStreamIndex]
        mov     bx,ax
        shl     bx,1
        shl     bx,1
        shl     bx,1
        mov     si,Streams
        add     si,bx

        ; BX = VRAM byte column for this stream.
        xor     bx,bx
        mov     bl,[si+ST_X]

        ; DX = physical Y = OriginY + cell*16, modulo 400.
        xor     ax,ax
        mov     al,[MutationCell]
        shl     ax,1
        shl     ax,1
        shl     ax,1
        shl     ax,1
        add     ax,[OriginY]

.mut_y_mod:
        cmp     ax,400
        jb      .mut_y_ready
        sub     ax,400
        jmp     .mut_y_mod

.mut_y_ready:
        mov     dx,ax

        ; Choose replacement glyph 0..9.
        call    Rand16
.mut_glyph_mod:
        cmp     al,GLYPH_COUNT
        jb      .mut_glyph_ready
        sub     al,GLYPH_COUNT
        jmp     .mut_glyph_mod

.mut_glyph_ready:
        mov     [MutationGlyph],al

        ; Ordinary mutations are usually normal, occasionally HOT or inverse.
        mov     byte [MutationEffect],0
        call    Rand16
        and     al,0x0F
        cmp     al,1
        jne     .check_inverse_mut
        mov     byte [MutationEffect],1
        jmp     .draw_mutation
.check_inverse_mut:
        cmp     al,2
        jne     .draw_mutation
        mov     byte [MutationEffect],2

.draw_mutation:
        mov     al,[MutationGlyph]
        call    DrawMutatedSymbol16x16

.done:
        pop     bp
        pop     di
        pop     si
        pop     dx
        pop     cx
        pop     bx
        pop     ax
        ret

; ---------------------------------------------------------------------------
; Draw one complete 16x16 replacement glyph directly into circular Mode-7 VRAM.
;
; IN:
;   AL = glyph 0..9
;   BX = left byte-column
;   DX = physical top Y 0..399
;
; Unlike the scanline-entry renderer this draws all 16 rows at once, but only
; for ONE character, so the cost is just 32 VRAM byte writes per mutation.
; ---------------------------------------------------------------------------
DrawMutatedSymbol16x16:
        push    ax
        push    bx
        push    cx
        push    dx
        push    si
        push    di
        push    bp

        xor     ah,ah
        mov     si,ax
        shl     si,1
        shl     si,1
        shl     si,1
        shl     si,1
        shl     si,1                    ; glyph * 32
        add     si,FontBank

        mov     bp,dx
        mov     cx,16

.mut_row:
        cmp     bp,400
        jb      .mut_row_y_ok
        sub     bp,400
.mut_row_y_ok:

        ; Left half.
        mov     al,[si]
        call    ApplyMutationEffect
.mut_left_ready:
        mov     dx,bp
        call    WriteVRAMByte

        ; Right half.
        inc     bx
        mov     al,[si+16]
        call    ApplyMutationEffect
.mut_right_ready:
        mov     dx,bp
        call    WriteVRAMByte
        dec     bx

        inc     si
        inc     bp
        loop    .mut_row

        pop     bp
        pop     di
        pop     si
        pop     dx
        pop     cx
        pop     bx
        pop     ax
        ret

; ---------------------------------------------------------------------------
; Apply MutationEffect to one bitmap byte.
;   0 = normal
;   1 = HOT/thick
;   2 = inverse (bright 16x16 cell with dark glyph)
; ---------------------------------------------------------------------------
ApplyMutationEffect:
        cmp     byte [MutationEffect],1
        jne     .check_inverse
        call    MakeHot
        ret
.check_inverse:
        cmp     byte [MutationEffect],2
        jne     .normal
        not     al
.normal:
        ret

; ---------------------------------------------------------------------------
; Start a rapid flicker burst on a REAL occupied visible cell.
; Roughly 1/4 character periods attempt to start one. Only one burst is active
; at a time. The selected physical VRAM cell is stored so successive scanline
; ticks redraw the same falling character while the GAVDP moves around it.
; ---------------------------------------------------------------------------
MaybeStartRapidFlicker:
        push    ax
        push    bx
        push    cx
        push    dx
        push    si
        push    di
        push    bp

        cmp     byte [FlickerTicks],0
        jne     .done

        cmp     byte [GlitchBurst],0
        jne     .force_attempt

        call    Rand16
        and     al,0x03
        jnz     .done                     ; normal: ~1 in 4 character periods
        jmp     .attempt

.force_attempt:
        ; During a glitch burst, attempt a rapid flicker every character period.
        dec     byte [GlitchBurst]

.attempt:

        mov     bp,STREAM_COUNT

.try_stream:
        call    RandomStreamIndex
        xor     ah,ah
        mov     [FlickerStreamIndex],ax

        mov     di,ax
        shl     di,1
        add     di,OccupancyHistory
        mov     dx,[di]
        or      dx,dx
        jnz     .have_stream

        dec     bp
        jnz     .try_stream
        jmp     .done

.have_stream:
        ; Pick an occupied cell among 0..15.
        call    Rand16
        and     al,0x0F
        mov     [FlickerCell],al
        mov     cx,16

.find_cell:
        xor     bx,bx
        mov     bl,[FlickerCell]

        mov     ax,1
        push    cx
        mov     cl,bl
        shl     ax,cl
        pop     cx
        test    dx,ax
        jnz     .cell_found

        inc     byte [FlickerCell]
        and     byte [FlickerCell],0x0F
        loop    .find_cell
        jmp     .done

.cell_found:
        ; Stream -> X byte column.
        mov     ax,[FlickerStreamIndex]
        mov     bx,ax
        shl     bx,1
        shl     bx,1
        shl     bx,1
        mov     si,Streams
        add     si,bx

        xor     ax,ax
        mov     al,[si+ST_X]
        mov     [FlickerX],ax

        ; Physical top Y for the chosen character cell.
        xor     ax,ax
        mov     al,[FlickerCell]
        shl     ax,1
        shl     ax,1
        shl     ax,1
        shl     ax,1
        add     ax,[OriginY]
.fy_mod:
        cmp     ax,400
        jb      .fy_ready
        sub     ax,400
        jmp     .fy_mod
.fy_ready:
        mov     [FlickerY],ax

        ; 5 redraws over the next five scroll ticks.
        mov     byte [FlickerTicks],5
        mov     byte [FlickerPhase],0

.done:
        pop     bp
        pop     di
        pop     si
        pop     dx
        pop     cx
        pop     bx
        pop     ax
        ret

; ---------------------------------------------------------------------------
; While a burst is active, redraw the selected cell every scanline tick.
; Sequence intentionally obvious:
;   phase 0 normal
;   phase 1 HOT
;   phase 2 INVERSE
;   phase 3 HOT
;   phase 4 normal
; Each phase chooses a fresh random glyph.
; ---------------------------------------------------------------------------
UpdateRapidFlicker:
        push    ax
        push    bx
        push    dx

        cmp     byte [FlickerTicks],0
        je      .done

        call    Rand16
.fglyph_mod:
        cmp     al,GLYPH_COUNT
        jb      .fglyph_ready
        sub     al,GLYPH_COUNT
        jmp     .fglyph_mod
.fglyph_ready:
        mov     [MutationGlyph],al

        mov     al,[FlickerPhase]
        cmp     al,2
        jne     .not_inverse
        mov     byte [MutationEffect],2
        jmp     .draw
.not_inverse:
        test    al,1
        jz      .normal
        mov     byte [MutationEffect],1
        jmp     .draw
.normal:
        mov     byte [MutationEffect],0

.draw:
        mov     bx,[FlickerX]
        mov     dx,[FlickerY]
        mov     al,[MutationGlyph]
        call    DrawMutatedSymbol16x16

        inc     byte [FlickerPhase]
        dec     byte [FlickerTicks]

.done:
        pop     dx
        pop     bx
        pop     ax
        ret

; ---------------------------------------------------------------------------
; Return AL = random stream index 0..23.
; Used by the V7 mutation engine. Startup itself still uses ActivationOrder[].
; ---------------------------------------------------------------------------
RandomStreamIndex:
        call    Rand16
.reduce_stream:
        cmp     al,STREAM_COUNT
        jb      .stream_ready
        sub     al,STREAM_COUNT
        jmp     .reduce_stream
.stream_ready:
        ret

Rand16:
        mov     ax,[RandState]
        shr     ax,1
        jnc     .no_xor
        xor     ax,0xB400
.no_xor:
        mov     [RandState],ax
        ret

; ============================================================================
; Hardware screen shake
; ============================================================================
;
; ShakeCountdown counts scanline ticks until the next event.
; A shake lasts six scanline ticks and uses small X/Y offsets.
; C462 low bits supply horizontal displacement; C663/bit7 combination supplies
; vertical displacement through WriteVerticalOrigin.
;
; About half of shake events also start GlitchBurst=3, which makes the rapid
; character-flicker engine attempt an event for the next three character periods.
; ---------------------------------------------------------------------------

UpdateScreenShake:
        push    ax
        push    bx

        cmp     byte [ShakeActive],0
        jne     .continue_shake

        cmp     word [ShakeCountdown],0
        je      .start_shake

        dec     word [ShakeCountdown]
        jmp     .done

.start_shake:
        mov     byte [ShakeActive],1
        mov     byte [ShakePhase],0
        mov     byte [ShakeTicks],6

        ; Next shake after roughly 320..831 scanline ticks.
        call    Rand16
        and     ax,0x01FF
        add     ax,320
        mov     [ShakeCountdown],ax

        ; About half the shakes also cause a three-character-period glitch burst.
        call    Rand16
        test    al,1
        jnz     .continue_shake
        mov     byte [GlitchBurst],3

.continue_shake:
        ; phase 0..5 selects a deliberately asymmetric shake sequence.
        xor     bx,bx
        mov     bl,[ShakePhase]

        mov     al,[ShakeXTable+bx]
        mov     [ShakeXOffset],al

        mov     al,[ShakeYTable+bx]
        mov     [ShakeYOffset],al

        inc     byte [ShakePhase]
        dec     byte [ShakeTicks]
        jnz     .done

        mov     byte [ShakeActive],0
        mov     byte [ShakeXOffset],0
        mov     byte [ShakeYOffset],0

.done:
        pop     bx
        pop     ax
        ret

; ============================================================================
; Reset / clear
; ============================================================================

ResetRain:
        push    ax
        push    bx
        push    cx
        push    di
        push    si

        call    ClearMonoScreen

        mov     word [OriginY],0
        mov     byte [PixelPhase],0
        ; Seed the LFSR from DOS clock so each launch/restart can differ.
        ; INT 21h AH=2Ch returns CH=hour, CL=minute, DH=second, DL=1/100 sec.
        mov     ah,0x2C
        int     0x21
        mov     ax,cx
        xor     ax,dx
        or      ax,ax
        jnz     .seed_ok
        mov     ax,0xACE1
.seed_ok:
        mov     [RandState],ax

        mov     byte [RampCounter],0
        mov     byte [EnabledStreams],0
        mov     byte [FlickerTicks],0
        mov     byte [FlickerPhase],0
        mov     byte [GlitchBurst],0
        mov     byte [ShakeActive],0
        mov     byte [ShakeTicks],0
        mov     byte [ShakePhase],0
        mov     byte [ShakeXOffset],0
        mov     byte [ShakeYOffset],0

        ; Randomized initial delay before first shake: 320..831 scanline ticks.
        call    Rand16
        and     ax,0x01FF
        add     ax,320
        mov     [ShakeCountdown],ax

        call    WriteVerticalOrigin

        mov     si,Streams
        mov     cx,STREAM_COUNT

.clear_streams:
        mov     byte [si+ST_ENABLED],0
        mov     byte [si+ST_WAIT],0
        mov     byte [si+ST_ACTIVE],0
        mov     byte [si+ST_TOTAL],0
        mov     byte [si+ST_GLYPH],0xFF
        mov     byte [si+ST_LEVEL],0
        mov     byte [si+ST_HOT],0

        add     si,STREAM_SIZE
        loop    .clear_streams

        ; Clear occupancy history for all 24 streams.
        mov     di,OccupancyHistory
        mov     cx,STREAM_COUNT
.clear_occupancy:
        mov     word [di],0
        add     di,2
        loop    .clear_occupancy

        ; Shuffle all 24 stream indices, then enable the first shuffled stream.
        call    ShuffleActivationOrder

        xor     bx,bx
        mov     bl,[ActivationOrder]
        shl     bx,1
        shl     bx,1
        shl     bx,1                       ; index * 8
        mov     si,Streams
        add     si,bx
        mov     byte [si+ST_ENABLED],1
        mov     byte [EnabledStreams],1

        pop     si
        pop     di
        pop     cx
        pop     bx
        pop     ax
        ret

ClearMonoScreen:
        push    ax
        push    cx
        push    dx
        push    si
        push    di
        push    es

        cld
        xor     si,si
        mov     dx,VRAM_COLS

.column:
        mov     ax,VRAM_UPPER_SEG
        mov     es,ax
        mov     di,si
        xor     ax,ax
        mov     cx,VRAM_BANK_ROWS/2
        rep     stosw

        mov     ax,VRAM_LOWER_SEG
        mov     es,ax
        mov     di,si
        xor     ax,ax
        mov     cx,VRAM_BANK_ROWS/2
        rep     stosw

        add     si,VRAM_COL_STRIDE
        dec     dx
        jnz     .column

        pop     es
        pop     di
        pop     si
        pop     dx
        pop     cx
        pop     ax
        ret

; ============================================================================
; QX-11 INT 71h ticker interval control
; ============================================================================
TICKER_ADDR         equ 0x2180
TICKER_DEFAULT      equ 0x0600
TICKER_MIN          equ 0x0100
TICKER_MAX          equ 0x0F00
TICKER_STEP         equ 0x0100

ReadTickerInterval:
        push    es
        xor     ax,ax
        mov     es,ax
        mov     ax,[es:TICKER_ADDR]
        pop     es
        ret

WriteTickerInterval:
        push    bx
        push    es
        mov     bx,ax
        xor     ax,ax
        mov     es,ax
        mov     [es:TICKER_ADDR],bx
        pop     es
        pop     bx
        ret

RestoreDefaultTicker:
        push    ax
        mov     ax,TICKER_DEFAULT
        mov     [TickerInterval],ax
        call    WriteTickerInterval
        pop     ax
        ret

IncreaseTickerSpeed:
        push    ax
        mov     ax,[TickerInterval]
        cmp     ax,TICKER_MIN
        jbe     .done
        sub     ax,TICKER_STEP
        cmp     ax,TICKER_MIN
        jae     .store
        mov     ax,TICKER_MIN
.store:
        mov     [TickerInterval],ax
        call    WriteTickerInterval
        call    SyncDelayFromTicker
.done:
        pop     ax
        ret

DecreaseTickerSpeed:
        push    ax
        mov     ax,[TickerInterval]
        cmp     ax,TICKER_MAX
        jae     .done
        add     ax,TICKER_STEP
        cmp     ax,TICKER_MAX
        jbe     .store
        mov     ax,TICKER_MAX
.store:
        mov     [TickerInterval],ax
        call    WriteTickerInterval
        call    SyncDelayFromTicker
.done:
        pop     ax
        ret

; 0600h -> 4000h, 0300h -> 2000h.
; DelayCount ~= TickerInterval * 32 / 3.
SyncDelayFromTicker:
        push    ax
        push    bx
        push    dx
        mov     ax,[TickerInterval]
        mov     bx,32
        mul     bx
        mov     bx,3
        div     bx
        cmp     ax,0x0800
        jae     .high
        mov     ax,0x0800
        jmp     .save
.high:
        cmp     ax,0xA000
        jbe     .save
        mov     ax,0xA000
.save:
        mov     [DelayCount],ax
        pop     dx
        pop     bx
        pop     ax
        ret

; ============================================================================
; Keyboard / timing
; ============================================================================

PollKeyboard:
        mov     ah,0x01
        int     0x16
        jnz     .ready
        ret

.ready:
        xor     ah,ah
        int     0x16

        cmp     al,0
        jne     .ascii_key
        cmp     ah,0x48
        je      .ticker_faster
        cmp     ah,0x50
        je      .ticker_slower
        ret

.ticker_faster:
        call    IncreaseTickerSpeed
        ret

.ticker_slower:
        call    DecreaseTickerSpeed
        ret

.ascii_key:
        cmp     al,0x1B
        jne     .not_escape
        mov     byte [ExitRequested],1
        ret

.not_escape:
        cmp     al,' '
        jne     .not_space
        xor     byte [Paused],1
        ret

.not_space:
        cmp     al,'1'
        jne     .not1
        mov     word [DelayCount],0x8000
        ret

.not1:
        cmp     al,'2'
        jne     .not2
        mov     word [DelayCount],0x4000
        ret

.not2:
        cmp     al,'3'
        jne     .not3
        mov     word [DelayCount],0x2000
        ret

.not3:
        cmp     al,'4'
        jne     .not4
        mov     word [DelayCount],0x0800
        ret

.not4:
        cmp     al,'r'
        je      .reset
        cmp     al,'R'
        jne     .done

.reset:
        call    ResetRain

.done:
        ret

FrameDelay:
        push    cx
        mov     cx,[DelayCount]
.wait:
        nop
        loop    .wait
        pop     cx
        ret

